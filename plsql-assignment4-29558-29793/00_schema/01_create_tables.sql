-- Clean start: drop old tables if they exist
BEGIN
  FOR t IN (SELECT table_name
            FROM user_tables
            WHERE table_name IN ('ERROR_LOG','SALARY_HISTORY','EMPLOYEE','JOB','DEPARTMENT'))
  LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

-- 1. DEPARTMENT
CREATE TABLE department (
  department_id    NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
  department_name  VARCHAR2(50) NOT NULL,
  location         VARCHAR2(50),
  CONSTRAINT pk_department PRIMARY KEY (department_id),
  CONSTRAINT uq_department_name UNIQUE (department_name)
);

-- 2. JOB
CREATE TABLE job (
  job_id      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
  job_title   VARCHAR2(50) NOT NULL,
  min_salary  NUMBER(10,2) NOT NULL,
  max_salary  NUMBER(10,2) NOT NULL,
  CONSTRAINT pk_job PRIMARY KEY (job_id),
  CONSTRAINT uq_job_title UNIQUE (job_title),
  CONSTRAINT ck_job_min_salary CHECK (min_salary > 0),
  CONSTRAINT ck_job_salary_range CHECK (max_salary >= min_salary)
);

-- 3. EMPLOYEE
CREATE TABLE employee (
  employee_id    NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  first_name     VARCHAR2(50)  NOT NULL,
  last_name      VARCHAR2(50)  NOT NULL,
  email          VARCHAR2(100) NOT NULL,
  hire_date      DATE DEFAULT SYSDATE NOT NULL,
  salary         NUMBER(10,2)  NOT NULL,
  status         VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
  job_id         NUMBER NOT NULL,
  department_id  NUMBER NOT NULL,
  manager_id     NUMBER,
  CONSTRAINT pk_employee PRIMARY KEY (employee_id),
  CONSTRAINT uq_employee_email UNIQUE (email),
  CONSTRAINT ck_employee_salary CHECK (salary > 0),
  CONSTRAINT ck_employee_status CHECK (status IN ('ACTIVE','INACTIVE')),
  CONSTRAINT fk_employee_job FOREIGN KEY (job_id) REFERENCES job (job_id),
  CONSTRAINT fk_employee_department FOREIGN KEY (department_id) REFERENCES department (department_id),
  CONSTRAINT fk_employee_manager FOREIGN KEY (manager_id) REFERENCES employee (employee_id)
);

-- 4. SALARY_HISTORY
CREATE TABLE salary_history (
  history_id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
  employee_id  NUMBER NOT NULL,
  old_salary   NUMBER(10,2) NOT NULL,
  new_salary   NUMBER(10,2) NOT NULL,
  change_date  DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_salary_history PRIMARY KEY (history_id),
  CONSTRAINT fk_history_employee FOREIGN KEY (employee_id) REFERENCES employee (employee_id)
);

-- 5. ERROR_LOG (used later for bulk processing errors)
CREATE TABLE error_log (
  log_id         NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
  error_source   VARCHAR2(100),
  error_message  VARCHAR2(500),
  logged_at      DATE DEFAULT SYSDATE,
  CONSTRAINT pk_error_log PRIMARY KEY (log_id)
);

-- Check: show the 5 tables
SELECT table_name
FROM user_tables
WHERE table_name IN ('DEPARTMENT','JOB','EMPLOYEE','SALARY_HISTORY','ERROR_LOG')
ORDER BY table_name;

-- Check: show all constraints
SELECT table_name, constraint_name,
       DECODE(constraint_type,'P','PRIMARY KEY','U','UNIQUE','R','FOREIGN KEY','C','CHECK') AS constraint_type
FROM user_constraints
WHERE table_name IN ('DEPARTMENT','JOB','EMPLOYEE','SALARY_HISTORY','ERROR_LOG')
  AND constraint_name NOT LIKE 'SYS_C%'
ORDER BY table_name, constraint_type;